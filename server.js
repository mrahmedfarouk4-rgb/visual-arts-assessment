app.get('/api/evaluations/batch', async (req, res) => {
  try {
    const { evaluation_ids, student_ids, grade_id, subject_id, evaluation_type, mode, eval_label } = req.query;

    // Case 1: Specific evaluation IDs requested
    if (evaluation_ids) {
      const eids = String(evaluation_ids).split(',').map(id => parseInt(id.trim())).filter(Boolean);
      const evals = await prisma.evaluation.findMany({
        where: { id: { in: eids } },
        orderBy: { id: 'asc' }
      });
      const results = await Promise.all(evals.map(async (ev) => {
        const student = await prisma.student.findUnique({ where: { id: ev.studentId } });
        if (!student) return null;
        let parsedScores = {};
        if (ev.scores) {
          try {
            parsedScores = typeof ev.scores === 'string' ? JSON.parse(ev.scores) : ev.scores;
          } catch (e) {
            console.error('Error parsing scores:', e);
          }
        }
        return { student, evaluation: { ...ev, scores: parsedScores } };
      }));
      return res.json(results.filter(Boolean));
    }

    // Case 2: By student IDs or all students of a grade
    if (!grade_id || !subject_id || !evaluation_type) {
      return res.status(400).json({ error: 'Missing required query parameters: grade_id, subject_id, evaluation_type' });
    }

    let ids = [];
    if (student_ids && student_ids !== 'all') {
      ids = String(student_ids).split(',').map(id => parseInt(id.trim())).filter(Boolean);
    } else {
      const allStudents = await prisma.student.findMany({
        where: {
          OR: [
            { gradeId: grade_id },
            { gradeId: null },
            { gradeId: '' }
          ]
        },
        orderBy: { id: 'asc' }
      });
      ids = allStudents.map(s => s.id);
    }

    const flatResults = [];
    for (const sid of ids) {
      const student = await prisma.student.findUnique({ where: { id: sid } });
      if (!student) continue;

      const whereClause = {
        studentId: sid,
        gradeId: grade_id,
        subjectId: subject_id,
        evaluationType: evaluation_type
      };

      const evals = await prisma.evaluation.findMany({
        where: whereClause,
        orderBy: { id: 'asc' }
      });

      if (evals.length === 0) continue;

      let filteredEvals = evals;

      // Filter by eval_label if specified (e.g. "التقييم الأول")
      if (eval_label && eval_label !== 'all') {
        filteredEvals = evals.filter(ev => {
          let ps = {};
          try { ps = typeof ev.scores === 'string' ? JSON.parse(ev.scores) : (ev.scores || {}); } catch (e) {}
          return ps._evaluationLabel === eval_label;
        });
      } else if (mode === 'latest') {
        filteredEvals = [evals[evals.length - 1]];
      }

      for (const ev of filteredEvals) {
        let parsedScores = {};
        if (ev && ev.scores) {
          try {
            parsedScores = typeof ev.scores === 'string' ? JSON.parse(ev.scores) : ev.scores;
          } catch (e) {
            console.error(`Error parsing scores for student ${sid}:`, e);
          }
        }
        flatResults.push({ student, evaluation: { ...ev, scores: parsedScores } });
      }
    }

    res.json(flatResults);
  } catch (error) {
    console.error('Batch fetch error:', error);
    res.status(500).json({ error: 'Internal server error', details: error.message });
  }
});

